/**
 * Writes data.js for the hype video from the registries, so no count or
 * name in the video is typed by hand: components from
 * src/components/registry.json, semantic tokens from src/tokens/registry.json,
 * themes from THEME_PRESETS in website/src/lib/theme/presets.ts (plus the base
 * look, BASE_THEME_ID), and SITE_URL and PACKAGE_NAME from scripts/brand.mjs. Run it again whenever those change.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { execSync } from 'node:child_process';

const root = execSync('git rev-parse --show-toplevel').toString().trim();
const read = (p) => readFileSync(`${root}/${p}`, 'utf8');

const components = JSON.parse(read('src/components/registry.json')).components.map((c) => c.label);
const tokenCount = Object.values(JSON.parse(read('src/tokens/registry.json')).categories).flat().length;
const presets = read('website/src/lib/theme/presets.ts');
const body = presets.slice(presets.indexOf('export const THEME_PRESETS'), presets.indexOf('\n};', presets.indexOf('export const THEME_PRESETS')));
const themes = body.split(/^ {2}(?=\w+: \{$)/m).slice(1).map((block) => ({
  id: block.match(/^(\w+)/)[1],
  label: block.match(/^ {4}label: "([^"]+)"/m)[1],
  brand: block.match(/^ {4}brand: "(#[0-9A-Fa-f]{6})"/m)[1],
}));
const baseId = read('website/src/lib/theme/brand.ts').match(/BASE_THEME_ID = "(\w+)"/)[1];
const baseBrand = read('src/tokens/tokens-primitives.css').match(/--primitive-teal-08: (#[0-9A-Fa-f]{6})/)[1];
themes.unshift({ id: baseId, label: baseId[0].toUpperCase() + baseId.slice(1), brand: baseBrand });
const siteUrl = read('scripts/brand.mjs').match(/SITE_URL = '([^']+)'/)[1];
const packageName = read('scripts/brand.mjs').match(/PACKAGE_NAME = '([^']+)'/)[1];

writeFileSync(new URL('./data.js', import.meta.url),
  `// GENERATED by build-data.mjs. Do not edit.\nwindow.RIFT = ${JSON.stringify({ components, tokenCount, themes, siteUrl, packageName }, null, 1)};\n`);
console.log(`components ${components.length}, tokens ${tokenCount}, themes ${themes.length}`);
