#!/usr/bin/env node
/**
 * generate-google-font-index.mjs
 *
 * Writes website/src/data/google-fonts.generated.ts: every Google Fonts
 * family by name, with the weights it can be requested at, plus the table of
 * stand-ins the playground uses for well-known faces Google does not carry.
 *
 * Why it exists: the playground reads a DESIGN.md file in the visitor's
 * browser and matches its typefaces (website/src/lib/theme/design-md.ts).
 * A face Google carries is loaded exactly; anything else gets the closest
 * Google face. Both decisions need to know, with no network request, which
 * names Google serves and at which weights, because Google's css2 endpoint
 * rejects a whole request that lists a weight the family lacks. The
 * playground imports the file lazily, on a DESIGN.md drop, so it costs the
 * page nothing until then.
 *
 * Source: the font metadata Next ships for `next/font/google`, which is
 * already installed and pinned by the lockfile, so the output is
 * deterministic and needs no network. A Next upgrade that changes the
 * catalogue regenerates the file, and CI's drift guard catches a stale
 * commit.
 *
 * SUBSTITUTES is the one hand-written part: well-known proprietary or system
 * faces mapped to the Google face nearest in build and feel. It lives here,
 * not in the playground, so generation fails when a stand-in names a family
 * the catalogue does not hold; a typo cannot degrade a match silently.
 *
 * Encoding (kept small, since the catalogue is large): each family maps to a
 * string. "v1-9" is a variable face with a weight axis from 100 to 900;
 * "3,4,7" lists static weights in hundreds. Only upright styles count.
 *
 * Runs in the validate-registry chain and the website's predev/prebuild;
 * scripts/validate-google-font-index.mjs holds the committed file to it.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
export const outputPath = join(root, 'website/src/data/google-fonts.generated.ts');

/**
 * Proprietary or system faces → the nearest Google family. Keys are matched
 * case-insensitively against the start of a family name, so "SF Pro" covers
 * "SF Pro Display" and "SF Pro Text". Longest key wins.
 */
export const SUBSTITUTES = {
  'SF Pro': 'Inter',
  'San Francisco': 'Inter',
  '-apple-system': 'Inter',
  'BlinkMacSystemFont': 'Inter',
  'system-ui': 'Inter',
  'Helvetica Neue': 'Inter',
  'Helvetica': 'Inter',
  'Arial': 'Inter',
  'Segoe UI': 'Open Sans',
  'Saans': 'Inter',
  'Graphik': 'Inter',
  'Suisse': 'Inter',
  'Neue Haas': 'Inter',
  'Söhne': 'Inter',
  'Sohne': 'Inter',
  'Circular': 'DM Sans',
  'Gilroy': 'Plus Jakarta Sans',
  'Proxima Nova': 'Montserrat',
  'Gotham': 'Montserrat',
  'Optimistic': 'Montserrat',
  'Avenir': 'Nunito Sans',
  'Futura': 'Jost',
  'Product Sans': 'Poppins',
  'Google Sans': 'Poppins',
  'Aeonik': 'Manrope',
  'Untitled Sans': 'Inter',
  'GT America': 'Inter',
  'GT Walsheim': 'DM Sans',
  'Basier': 'DM Sans',
  'Euclid': 'Plus Jakarta Sans',
  'Georgia': 'Lora',
  'Times': 'Lora',
  'Tiempos': 'Lora',
  'Freight': 'Lora',
  'SF Mono': 'IBM Plex Mono',
  'Menlo': 'IBM Plex Mono',
  'Monaco': 'IBM Plex Mono',
  'Consolas': 'IBM Plex Mono',
  'Courier': 'IBM Plex Mono',
};

function readCatalogue() {
  const requireFromSite = createRequire(join(root, 'website/package.json'));
  const nextDir = dirname(requireFromSite.resolve('next/package.json'));
  const dataPath = join(nextDir, 'dist/compiled/@next/font/dist/google/font-data.json');
  return JSON.parse(readFileSync(dataPath, 'utf8'));
}

const encode = (meta) => {
  const axis = (meta.axes ?? []).find((a) => a.tag === 'wght');
  if (axis) return `v${Math.round(axis.min / 100)}-${Math.round(axis.max / 100)}`;
  const weights = (meta.weights ?? [])
    .filter((w) => /^\d+$/.test(w))
    .map((w) => Math.round(Number(w) / 100));
  return [...new Set(weights)].sort((a, b) => a - b).join(',');
};

export function assembleGoogleFontIndex() {
  const catalogue = readCatalogue();
  const names = Object.keys(catalogue)
    .filter((name) => (catalogue[name].styles ?? ['normal']).includes('normal'))
    .sort((a, b) => a.localeCompare(b, 'en'));

  const missing = Object.entries(SUBSTITUTES).filter(([, target]) => !catalogue[target]);
  if (missing.length > 0) {
    throw new Error(
      `SUBSTITUTES names families Google does not carry: ${missing
        .map(([key, target]) => `${key} → ${target}`)
        .join(', ')}`,
    );
  }

  const lines = [
    '// GENERATED by scripts/generate-google-font-index.mjs — never hand-edit.',
    '// Regenerate with: node scripts/generate-google-font-index.mjs',
    '',
    '/** Every Google Fonts family with upright styles, and its weights: "v1-9"',
    '    is a variable weight axis in hundreds, "3,4,7" lists static weights. */',
    'export const GOOGLE_FONTS: Readonly<Record<string, string>> = {',
    ...names.map((name) => `  ${JSON.stringify(name)}: ${JSON.stringify(encode(catalogue[name]))},`),
    '};',
    '',
    '/** Well-known faces Google does not carry → the nearest Google family. */',
    'export const FONT_SUBSTITUTES: Readonly<Record<string, string>> = {',
    ...Object.entries(SUBSTITUTES).map(
      ([key, target]) => `  ${JSON.stringify(key)}: ${JSON.stringify(target)},`,
    ),
    '};',
    '',
  ];
  return lines.join('\n');
}

const isMain = process.argv[1] === fileURLToPath(import.meta.url);
if (isMain) {
  const content = assembleGoogleFontIndex();
  writeFileSync(outputPath, content);
  const count = (content.match(/^ {2}".+": "[v\d]/gm) ?? []).length;
  console.log(`✓ Google font index written (${count} families)`);
}
