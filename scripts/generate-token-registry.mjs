#!/usr/bin/env node
/**
 * Regenerates src/tokens/registry.json — the single source of truth for
 * the semantic-token count — from the token CSS files themselves
 * (tokens-light.css + tokens-typography.css + tokens-motion.css), so
 * displayed token counts can never drift from the CSS (see the
 * "Registries" section of CLAUDE.md).
 *
 * Categories are derived from the variable prefix. A token with an
 * unrecognized prefix fails the build on purpose: a new token category
 * has to be added to CATEGORY_PREFIXES here — and given a home on the
 * site — deliberately, not absorbed silently.
 *
 * Runs as part of `npm run validate-registry` (every build, both
 * projects). Never hand-edit src/tokens/registry.json.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const tokensDir = join(repoRoot, 'src', 'tokens');
const registryPath = join(tokensDir, 'registry.json');

/** The files that define the semantic layer (primitives are excluded). */
const SEMANTIC_FILES = ['tokens-light.css', 'tokens-typography.css', 'tokens-motion.css'];

/** Prefix → category mapping. Order is the display order on the site. */
const CATEGORY_PREFIXES = [
  ['colour', ['--color-']],
  ['typography', ['--font-']],
  ['spacing', ['--gap-', '--padding-']],
  ['radius', ['--radius-']],
  ['border', ['--border-']],
  ['shadow', ['--shadow-']],
  ['icons', ['--icon-size-']],
  ['motion', ['--motion-']],
];

/** All custom-property names defined in a CSS source string. */
export function parseTokenNames(css) {
  return [...css.matchAll(/^\s*(--[a-z0-9-]+)\s*:/gim)].map((m) => m[1]);
}

/** Derive { categories: { colour: [...], ... } } from the semantic CSS files. */
export function deriveTokenRegistry() {
  const categories = Object.fromEntries(
    CATEGORY_PREFIXES.map(([category]) => [category, []])
  );
  const seen = new Set();
  const uncategorized = [];

  for (const file of SEMANTIC_FILES) {
    const css = readFileSync(join(tokensDir, file), 'utf8');
    for (const name of parseTokenNames(css)) {
      if (seen.has(name)) continue;
      seen.add(name);
      const match = CATEGORY_PREFIXES.find(([, prefixes]) =>
        prefixes.some((prefix) => name.startsWith(prefix))
      );
      if (!match) {
        uncategorized.push(`${name} (${file})`);
        continue;
      }
      categories[match[0]].push(name);
    }
  }

  if (uncategorized.length > 0) {
    throw new Error(
      `Semantic tokens with no category — add their prefix to CATEGORY_PREFIXES ` +
        `in scripts/generate-token-registry.mjs (and give the category a home on the site):\n` +
        uncategorized.map((t) => `    - ${t}`).join('\n')
    );
  }

  for (const names of Object.values(categories)) names.sort();
  return { categories };
}

export function summarize(categories) {
  const perCategory = Object.entries(categories)
    .map(([category, names]) => `${category} ${names.length}`)
    .join(', ');
  const total = Object.values(categories).reduce((sum, names) => sum + names.length, 0);
  return { total, perCategory };
}

const isMain = import.meta.url === pathToFileURL(process.argv[1]).href;
if (isMain) {
  try {
    const { categories } = deriveTokenRegistry();
    const json =
      JSON.stringify(
        {
          '//': 'GENERATED by scripts/generate-token-registry.mjs from the semantic token CSS — never hand-edit; run `npm run validate-registry`.',
          categories,
        },
        null,
        2
      ) + '\n';

    let existing = null;
    try {
      existing = readFileSync(registryPath, 'utf8');
    } catch {
      /* first generation */
    }

    const { total, perCategory } = summarize(categories);
    if (existing === json) {
      console.log(`✓ Token registry up to date — ${total} semantic tokens (${perCategory}).`);
    } else {
      writeFileSync(registryPath, json);
      console.log(`✓ Token registry regenerated — ${total} semantic tokens (${perCategory}).`);
    }
  } catch (error) {
    console.error(`✗ ${error.message}`);
    process.exit(1);
  }
}
